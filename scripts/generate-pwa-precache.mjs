import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const allowedExtensions = new Set(['.js', '.css', '.svg', '.png', '.woff2'])

const walk = (directory) => {
  if (!fs.existsSync(directory)) return []
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const fullPath = path.join(directory, entry.name)
    return entry.isDirectory() ? walk(fullPath) : [fullPath]
  })
}

const relativePosix = (base, file) => path.relative(base, file).split(path.sep).join('/')
const unique = values => [...new Set(values)]

const playerRoot = path.join(root, 'public', 'music')
const playerUrls = unique([
  '/',
  '/manifest.json',
  ...walk(playerRoot)
    .filter(file => allowedExtensions.has(path.extname(file).toLowerCase()))
    .filter(file => !['sw.js'].includes(path.basename(file)))
    .map(file => `/_player/${relativePosix(playerRoot, file)}`),
  '/js/notification-engine.js',
  '/admin/js/library-integration.js',
]).filter(url => {
  const file = url === '/'
    ? path.join(playerRoot, 'index.html')
    : url === '/manifest.json'
      ? path.join(playerRoot, 'manifest.json')
      : url.startsWith('/_player/')
        ? path.join(playerRoot, url.slice('/_player/'.length))
        : url.startsWith('/admin/')
          ? path.join(root, 'public', url.slice('/admin/'.length))
          : path.join(root, 'public', url.slice(1))
  return fs.existsSync(file)
})

const adminRoot = path.join(root, 'public')
const adminUrls = unique([
  './',
  './index.html',
  ...walk(adminRoot)
    .filter(file => !relativePosix(adminRoot, file).startsWith('music/'))
    .filter(file => allowedExtensions.has(path.extname(file).toLowerCase()) || path.basename(file) === 'manifest.json')
    .filter(file => !['sw.js', 'config.js'].includes(path.basename(file)))
    .map(file => `./${relativePosix(adminRoot, file)}`),
  ...walk(path.join(playerRoot, 'assets'))
    .filter(file => allowedExtensions.has(path.extname(file).toLowerCase()))
    .map(file => `/_player/assets/${relativePosix(path.join(playerRoot, 'assets'), file)}`),
])

const updateWorker = (relativeWorker, urls) => {
  const workerPath = path.join(root, relativeWorker)
  const source = fs.readFileSync(workerPath, 'utf8')
  const replacement = [
    '// PRECACHE:START - generated by scripts/generate-pwa-precache.mjs',
    'const PRECACHE_URLS = [',
    ...urls.map(url => `    ${JSON.stringify(url)},`),
    '];',
    '// PRECACHE:END',
  ].join('\n')
  const updated = source.replace(
    /\/\/ PRECACHE:START[^\n]*\n[\s\S]*?\/\/ PRECACHE:END/,
    replacement,
  )
  if (updated === source && !source.includes('// PRECACHE:START')) throw new Error(`Precache markers missing in ${relativeWorker}`)
  fs.writeFileSync(workerPath, updated, 'utf8')
  console.log(`Generated ${urls.length} precache entries in ${relativeWorker}`)
}

updateWorker('public/music/sw.js', playerUrls)
updateWorker('public/sw.js', adminUrls)
